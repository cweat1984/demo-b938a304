"""Preprocess the USGS/LBNL/ACP U.S. Wind Turbine Database (public domain) into compact app data.
Input: data-src/uswtdb_V9_1_20260928.csv  (https://energy.usgs.gov/uswtdb/data/)
Output: src/data/wind/farms.json, src/data/wind/t/<ST>.json, src/data/wind/demo.ts
"""
import csv, json, re, collections, os, statistics
SRC = '/workspace/southern-app/data-src/uswtdb_V9_1_20260928.csv'
OUT = '/workspace/southern-app/app/src/data/wind'
VERSION, VDATE = '9.1', '2026-09-28'
def num(v):
    try: return float(v)
    except: return None
rows = [r for r in csv.DictReader(open(SRC)) if r['t_offshore'] != '1']
proj = collections.defaultdict(list)
for r in rows: proj[(r['p_name'] or 'Unnamed project', r['t_state'])].append(r)
farms, turb, ids = [], collections.defaultdict(dict), set()
for (name, st), rs in sorted(proj.items(), key=lambda x: (x[0][1], x[0][0])):
    base = (st + '-' + re.sub(r'[^a-z0-9]+', '-', name.lower()).strip('-'))[:60]; fid = base; i = 2
    while fid in ids: fid = f'{base}-{i}'; i += 1
    ids.add(fid)
    mk = collections.OrderedDict()
    for r in rs:
        k = (r['t_manu'] or 'Unknown', r['t_model'] or 'Unknown')
        m = mk.setdefault(k, {'manu': k[0], 'model': k[1], 'n': 0, 'kw': num(r['t_cap']), 'hh': num(r['t_hh']), 'rd': num(r['t_rd']), 'th': num(r['t_ttlh'])})
        m['n'] += 1
    models = sorted(mk.values(), key=lambda m: -m['n'])
    idx = {(m['manu'], m['model']): i for i, m in enumerate(models)}
    lat = round(statistics.fmean(float(r['ylat']) for r in rs), 5); lng = round(statistics.fmean(float(r['xlong']) for r in rs), 5)
    counties = sorted(set(r['t_county'].replace(' County', '') for r in rs if r['t_county']))
    years = [int(r['p_year']) for r in rs if r['p_year'].isdigit()]
    caps = [num(r['p_cap']) for r in rs if num(r['p_cap'])]
    mw = caps[0] if caps else round(sum((m['kw'] or 0) * m['n'] for m in models) / 1000, 1)
    farms.append({'id': fid, 'name': name, 'st': st, 'county': ', '.join(counties[:3]), 'lat': lat, 'lng': lng, 'n': len(rs), 'mw': mw, 'year': min(years) if years else None, 'eia': rs[0]['eia_id'] or None,
                  'models': [{k: (round(v, 1) if isinstance(v, float) else v) for k, v in m.items()} for m in models]})
    turb[st][fid] = [[int(r['case_id']), r['faa_ors'] or '', round(float(r['xlong']), 5), round(float(r['ylat']), 5), idx[(r['t_manu'] or 'Unknown', r['t_model'] or 'Unknown')]] for r in sorted(rs, key=lambda r: float(r['xlong']))]
json.dump({'meta': {'source': 'U.S. Wind Turbine Database (USWTDB), USGS / LBNL / American Clean Power', 'version': VERSION, 'date': VDATE, 'doi': 'https://doi.org/10.5066/F7TX3DN0', 'license': 'Public domain', 'turbines': len(rows), 'projects': len(farms)}, 'farms': farms}, open(f'{OUT}/farms.json', 'w'), separators=(',', ':'))
for st, d in turb.items(): json.dump(d, open(f'{OUT}/t/{st}.json', 'w'), separators=(',', ':'))
# --- demo links: seeded wind sites -> real farms (turbines sorted west→east become T-1..T-n for the demo labels)
DEMO = {'Sooner Ridge Wind': ('OK', 'Keenan II', [18, 22]), 'Canadian Hills Wind': ('OK', 'Canadian Hills', [41]), 'Panhandle Wind': ('OK', 'Gruver Wind', [7, 8]), 'Amarillo Wind Hub': ('TX', 'Majestic II', [12]), 'Childress Wind': ('TX', 'Foard City', [64]), 'Sweetwater Wind': ('TX', 'Sweetwater Phase II', [5])}
demo = {}
for site, (st, pname, picks) in DEMO.items():
    f = next(x for x in farms if x['name'] == pname and x['st'] == st); ts = turb[st][f['id']]
    lats = [t[3] for t in ts]; lngs = [t[2] for t in ts]
    om = {'lat': round(min(lats) - 0.022, 5), 'lng': round(statistics.median(lngs), 5)}
    demo[site] = {'farmId': f['id'], 'farmName': pname, 'lat': f['lat'], 'lng': f['lng'], 'model': f['models'][0]['manu'] + ' ' + f['models'][0]['model'], 'hh': f['models'][0]['hh'],
                  'turbines': [{'caseId': ts[p - 1][0], 'label': f'T-{p}', 'lat': ts[p - 1][3], 'lng': ts[p - 1][2]} for p in picks], 'om': om, 'count': len(ts)}
open(f'{OUT}/demo.ts', 'w').write('// GENERATED by scripts/wind-prep.py: seeded wind sites linked to real USWTDB farms. Turbine labels T-n = west→east order (demo numbering).\nexport const WIND_DEMO: Record<string, { farmId: string; farmName: string; lat: number; lng: number; model: string; hh: number | null; count: number; om: { lat: number; lng: number }; turbines: { caseId: number; label: string; lat: number; lng: number }[] }> = ' + json.dumps(demo, indent=1) + '\n')
print(len(farms), 'farms', len(rows), 'turbines')
